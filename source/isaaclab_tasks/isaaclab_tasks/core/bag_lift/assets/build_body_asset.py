"""Build the deformable bag-body asset for the bag-lift task.

Run once (and again whenever the source bag USD changes):

    uv run python source/isaaclab_tasks/isaaclab_tasks/core/bag_lift/assets/build_body_asset.py

Writes next to this script:
    bag_body_deformable.usda   the bag body as one welded, watertight triangle mesh (Xform "Bag" > Mesh "mesh"), in
                               the bag frame (origin at the body centre, body z in [-0.076, 0.076])

Why a new mesh: the source body stores every triangle with its own three vertices (11556 points for 3852 triangles),
so no two triangles share a vertex. The tetrahedralizer behind PhysX volume deformables needs a connected,
watertight surface. Welding the vertices by position gives 1928 points and every edge shared by exactly two faces.
The script checks that and refuses to write the file otherwise.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np

from pxr import Gf, Usd, UsdGeom, Vt

HERE = Path(__file__).parent
BAG_USD = "/home/joshua/Documents/Rigid Bag.usd"
BODY_MESH = "/World/Part_Studio_1___Part_1/node_/mesh_"
WELD_TOL = 1.0e-6  # [m]


def body_mesh() -> tuple[np.ndarray, np.ndarray]:
    """(points (n, 3) in the bag frame, triangles (m, 3)) with coincident vertices welded."""
    stage = Usd.Stage.Open(BAG_USD)
    prim = stage.GetPrimAtPath(BODY_MESH)
    xf = UsdGeom.Xformable(prim).ComputeLocalToWorldTransform(0)
    mesh = UsdGeom.Mesh(prim)
    raw = np.array([list(xf.Transform(Gf.Vec3d(*p))) for p in mesh.GetPointsAttr().Get()])
    counts = np.array(mesh.GetFaceVertexCountsAttr().Get())
    assert (counts == 3).all(), "the body mesh is expected to be all triangles"
    tris = np.array(mesh.GetFaceVertexIndicesAttr().Get()).reshape(-1, 3)
    key = np.round(raw / WELD_TOL).astype(np.int64)
    _, first, inverse = np.unique(key, axis=0, return_index=True, return_inverse=True)
    points = raw[first]
    tris = np.asarray(inverse).reshape(-1)[tris]
    keep = (tris[:, 0] != tris[:, 1]) & (tris[:, 1] != tris[:, 2]) & (tris[:, 2] != tris[:, 0])
    return points, tris[keep]


def check_watertight(tris: np.ndarray) -> None:
    edges: dict[tuple[int, int], int] = {}
    for a, b, c in tris:
        for u, v in ((a, b), (b, c), (c, a)):
            k = (min(u, v), max(u, v))
            edges[k] = edges.get(k, 0) + 1
    bad = sum(1 for n in edges.values() if n != 2)
    if bad:
        raise SystemExit(f"[body] {bad} of {len(edges)} edges are not shared by exactly two faces: not watertight")


def write_body(points: np.ndarray, tris: np.ndarray) -> None:
    path = HERE / "bag_body_deformable.usda"
    stage = Usd.Stage.CreateNew(str(path))
    UsdGeom.SetStageUpAxis(stage, UsdGeom.Tokens.z)
    UsdGeom.SetStageMetersPerUnit(stage, 1.0)
    root = UsdGeom.Xform.Define(stage, "/Bag")
    stage.SetDefaultPrim(root.GetPrim())
    root.GetPrim().SetDocumentation(
        "Bag body as one welded watertight triangle mesh, in the bag frame. Generated by build_body_asset.py. "
        "Becomes a PhysX volume deformable when spawned with volume_deformable_props."
    )
    mesh = UsdGeom.Mesh.Define(stage, "/Bag/mesh")
    mesh.CreatePointsAttr(Vt.Vec3fArray.FromNumpy(points.astype(np.float32)))
    mesh.CreateFaceVertexCountsAttr(Vt.IntArray([3] * len(tris)))
    mesh.CreateFaceVertexIndicesAttr(Vt.IntArray.FromNumpy(tris.astype(np.int32).reshape(-1)))
    mesh.CreateSubdivisionSchemeAttr(UsdGeom.Tokens.none)
    mesh.CreateDoubleSidedAttr(True)
    mesh.CreateDisplayColorAttr([Gf.Vec3f(0.15, 0.3, 0.7)])
    stage.GetRootLayer().Save()


def main() -> None:
    points, tris = body_mesh()
    check_watertight(tris)
    write_body(points, tris)
    print(f"[body] {len(points)} vertices, {len(tris)} triangles, watertight")
    print(f"[body] bbox min {points.min(0).round(4)} max {points.max(0).round(4)}")
    print(f"[body] centroid of the vertices {points.mean(0).round(4)} (bag frame origin should be close to it)")


if __name__ == "__main__":
    main()
